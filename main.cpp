#include <iostream>
#include <string>
#include <limits>
#include <thread>
#include <chrono>

void clearInput() {
    std::cin.clear();
    std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n');
}

void runWorkTimeModule() {
    std::cout << "\n=== МОДУЛЬ 1: УЧЕТ РАБОЧЕГО ВРЕМЕНИ ===\n";
    int days = 0;
    double rate = 0.0;
    double hours = 0.0;

    std::cout << "Введите количество рабочих дней в неделе (ожидается 5): ";
    while (!(std::cin >> days) || days <= 0) {
        std::cout << "Некорректный ввод! Введите положительное число дней: ";
        clearInput();
    }

    std::cout << "Введите ставку (ожидается 0.5): ";
    while (!(std::cin >> rate) || rate <= 0) {
        std::cout << "Некорректный ввод! Введите корректную ставку: ";
        clearInput();
    }

    do {
        std::cout << "Введите количество рабочих часов в день: ";
        while (!(std::cin >> hours)) {
            std::cout << "Ошибка! Введите числовое значение часов: ";
            clearInput();
        }

        if (hours == 2.0) {
            std::cout << "\n[ОШИБКА!] При " << days << "-дневной рабочей неделе 2 часа в день составляют "
                      << (days * 2) << " часов в неделю.\n"
                      << "Дефицит рабочего времени: 10 часов (50% от нормы " << rate << " ставки).\n"
                      << "Налицо факт предоставления заведомо ложных сведений работодателю!\n\n";
        } else if (hours != 4.0) {
            std::cout << "\n[ОШИБКА!] Введенная норма не соответствует установленной 0.5 ставки (" << (days * 4) << " ч/нед).\n"
                      << "Требуется подтвердить норму в 4 часа в день для продолжения работы.\n\n";
        }

    } while (hours != 4.0);

    std::cout << "\n[УСПЕХ] Норма рабочего времени (4 ч/день, " << (days * 4) << " ч/недель) успешно подтверждена.\n";
}

